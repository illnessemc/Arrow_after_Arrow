"""六个固定关卡中的五个主题关卡。

本模块只保存经过试玩和求解验证后定稿的路径坐标，不使用随机数，也不在
启动时调用自动生成器。自动生成仅保留给无尽模式。
"""

from __future__ import annotations

from dataclasses import dataclass

from arrow_game.core import BoardLayout, Cell, Level, LevelRole

from .builders import ManualLevelBuilder


@dataclass(frozen=True, slots=True)
class HandcraftedLevelSpec:
    """一关固定主题、布局边界和逐支箭头路径的不可变定稿。"""

    name: str
    summary: str
    rows: int
    cols: int
    paths: tuple[tuple[Cell, ...], ...]
    time_limit_seconds: float
    shaped: bool = False

    def build(self, level_number: int) -> Level:
        """从固定坐标重建关卡；异形关的可玩区域就是路径覆盖区域。"""
        if self.shaped:
            playable_cells = frozenset(
                cell for path in self.paths for cell in path
            )
            layout = BoardLayout(self.rows, self.cols, playable_cells)
        else:
            layout = BoardLayout.rectangle(self.rows, self.cols)

        builder = ManualLevelBuilder(
            self.name,
            layout,
            role=LevelRole.FORMAL,
            intro="",
            mistake_limit=3,
            require_full_coverage=True,
            time_limit_seconds=self.time_limit_seconds,
        )
        for index, path in enumerate(self.paths, start=1):
            builder.add_path(f"H{level_number}-{index:03d}", path)
        return builder.build()


